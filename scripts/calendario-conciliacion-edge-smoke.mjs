import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
const edge=readFileSync("docs/edge/estado-financiero/index.ts","utf8");
const engine=readFileSync("docs/edge/estado-financiero/calendario-conciliacion.mjs","utf8");
const beta=readFileSync("docs/edge/estado-financiero/calendario-beta.mjs","utf8");
const client=readFileSync("docs/edge/estado-financiero/calendario-cliente.mjs","utf8");
let count=0;
const check=(x,msg)=>{assert(x,msg);count++};
check(edge.includes('import { reconciliarCalendarioOficial } from "./calendario-conciliacion.mjs"'),"Módulo único");
check(edge.includes('calendario.conciliacion=reconciliarCalendarioOficial({calendario,financiero:fq.data})'),"Conciliación solo con dato oficial");
const simulate=edge.indexOf('if(accion==="simular_calendario_beta")');
const guard=edge.indexOf('const admin=await verify(');
const clientEndpoint=edge.indexOf('if(accion==="mi_calendario")');
check(guard>clientEndpoint&&simulate>guard,"Simulador bajo token Admin");
const official=edge.slice(edge.indexOf('if(accion==="mi_estado")'),guard);
check(!official.includes('reconciliarCalendarioOficial('),"No sustituir deuda oficial");
check(!official.includes("calendario.conciliacion"),"No exponer simulación al cliente");
check(edge.includes('accion==="guardar_calendario_beta"'),"Fechas persisten con ruta existente");
check(edge.includes('if(accion==="mi_calendario")'),"Fechas sin importes bajo sesión cliente");
check(client.includes("puede_pagar_individual:false"),"Endpoint cliente no autoriza cobros");
check(beta.includes("listo_para_acreditar:false"),"Simulador no acredita");
check(engine.includes("desglose_de_obligaciones_autorizado:false"),"Conciliación no genera deuda");
check(engine.includes('fuente_financiera!=="supabase:goxion_estado_financiero"'),"Exige ledger oficial");
check(engine.includes("pago_parcial_o_revision"),"Controla revisión y pagos incompletos");
check(engine.includes("cupon_misiones_una_vez_por_periodo"),"Cupón idempotente pendiente de imputación");
check(engine.includes("mora_exige_dias_y_saldo_por_vencimiento"),"Mora por unidad no automática");
check(engine.includes("obligaciones_independientes_sin_aplicacion_idempotente"),"Pago por obligación bloqueado");
check(!/await\s+sb\.from\(|await\s+sb\.rpc\(|fetch\(/.test(engine),"Módulo puro sin escrituras ni llamadas");
console.log("GOXION Edge calendario-conciliación: "+count+" guardas PASS; oficial, cliente y pagos intactos");
